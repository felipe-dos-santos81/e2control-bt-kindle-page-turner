#!/usr/bin/env python3
"""Jieli/BTstack ATT database tables: generate the Kindle Click one, or dump any.

Entry layout (little endian): u16 size (whole entry), u16 flags, u16 handle, UUID (2 bytes,
16 if flags & 0x0200), value. A size of 0 ends the table.

  att_table.py gen              print ble_hogp_profile.h for the Kindle Click app
  att_table.py dump FILE [OFF]  walk a table: FILE is a .h (C byte array) or a binary;
                                in a binary the table is found by its GAP service entry
                                unless OFF (file offset) is given
"""
import re
import sys

READ, WRITE_WO_RSP, WRITE, NOTIFY, INDICATE = 0x02, 0x04, 0x08, 0x10, 0x20
DYNAMIC, UUID128, AUTHN, AUTHZ = 0x0100, 0x0200, 0x0400, 0x0800
ENC7 = (7 - 1) << 12        # encryption required, key size >= 7 (= hogp_sm_init_config.min_key_size)
PROP_NAMES = [(READ, 'READ'), (WRITE_WO_RSP, 'WRITE_WITHOUT_RESPONSE'), (WRITE, 'WRITE'),
              (NOTIFY, 'NOTIFY'), (INDICATE, 'INDICATE'), (DYNAMIC, 'DYNAMIC'),
              (UUID128, 'UUID128'), (AUTHN, 'AUTHENTICATION_REQUIRED'), (AUTHZ, 'AUTHORIZATION_REQUIRED')]

# (uuid16, characteristic properties, extra value flags, initial value or None, report reference or None)
# Value flags = properties | DYNAMIC (when value is None) | extra; a CCCD (with extra) follows NOTIFY/INDICATE values.
SERVICES = [
    (0x1800, [(0x2a00, READ, 0, None, None), (0x2a01, READ, 0, None, None), (0x2a04, READ, 0, None, None)]),
    (0x1801, [(0x2a05, INDICATE, 0, b'', None)]),
    (0x180a, [(u, READ, 0, None, None) for u in (0x2a29, 0x2a24, 0x2a25, 0x2a27, 0x2a26, 0x2a28, 0x2a23, 0x2a2a, 0x2a50)]),
    (0x180f, [(0x2a19, READ | NOTIFY, 0, None, None)]),
    (0x1812, [(0x2a4e, READ | WRITE_WO_RSP, ENC7, b'\x01', None),       # Protocol Mode: report protocol
              (0x2a4d, READ | NOTIFY, ENC7, None, b'\x01\x01'),        # Input Report, ID 1
              (0x2a4b, READ, ENC7, None, None),                        # Report Map
              (0x2a4a, READ, ENC7, None, None),                        # HID Information
              (0x2a4c, WRITE_WO_RSP, ENC7, None, None)]),              # HID Control Point
]


def entry(flags, handle, uuid, value=b''):
    return (6 + 2 + len(value)).to_bytes(2, 'little') + flags.to_bytes(2, 'little') + \
        handle.to_bytes(2, 'little') + uuid.to_bytes(2, 'little') + value


def build():
    """Return (table bytes, [(define name, handle)])."""
    out, names, h = b'', [], 1
    seen = {}
    for svc, chars in SERVICES:
        out += entry(READ, h, 0x2800, svc.to_bytes(2, 'little')); h += 1
        for uuid, props, extra, init, ref in chars:
            n = seen[uuid] = seen.get(uuid, 0) + 1
            stem = 'ATT_CHARACTERISTIC_%04x_%02d' % (uuid, n)
            out += entry(READ, h, 0x2803, bytes([props]) + (h + 1).to_bytes(2, 'little') + uuid.to_bytes(2, 'little')); h += 1
            vflags = props | extra | (DYNAMIC if init is None else 0)
            out += entry(vflags, h, uuid, init or b''); names.append((stem + '_VALUE_HANDLE', h)); h += 1
            if props & (NOTIFY | INDICATE):
                out += entry(READ | WRITE | DYNAMIC | extra, h, 0x2902, b'\x00\x00')
                names.append((stem + '_CLIENT_CONFIGURATION_HANDLE', h)); h += 1
            if ref:
                out += entry(READ, h, 0x2908, ref); h += 1     # readable during discovery, as stock and vendor
    return out + b'\x00\x00', names


def header():
    table, names = build()
    rows = ['    ' + ' '.join('0x%02x,' % b for b in table[i:i + 16]) for i in range(0, len(table), 16)]
    lines = ['// Generated by fw/att_table.py gen (Kindle Click app). Do not edit by hand.',
             '// Dump with: fw/att_table.py dump <this file>',
             '#ifndef _BLE_HOGP_PROFILE_H', '#define _BLE_HOGP_PROFILE_H', '', '#include <stdint.h>', '#include "app_config.h"', '',
             '#if RCSP_BTMATE_EN', '#error "this table has no RCSP (ae00) service; ble_hogp.c RCSP code needs it"', '#endif', '',
             'static const uint8_t hogp_profile_data[] = {'] + rows + ['};', '']
    lines += ['#define %s 0x%04x' % nh for nh in names]
    lines += ['', '//INPUT', '#define HID_REPORT_ID_01_SEND_HANDLE    ATT_CHARACTERISTIC_2a4d_01_VALUE_HANDLE', '', '#endif', '']
    return '\n'.join(lines)


def load(path, off=None):
    data = open(path, 'rb').read()
    if path.endswith('.h'):
        body = data.decode('utf-8', 'replace')
        body = body[body.index('{', body.index('hogp_profile_data')):]
        body = re.sub(r'//[^\n]*|/\*.*?\*/', '', body[:body.index('};')], flags=re.S)
        return bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', body)), 0
    if off is None:     # the GAP entry bytes can occur elsewhere too: take the longest valid table
        gap, cands, i = entry(READ, 1, 0x2800, b'\x00\x18'), [], -1
        while (i := data.find(gap, i + 1)) >= 0:
            cands.append((count(data, i), i))
        if not cands:
            sys.exit('no GAP service entry (handle 1, 0x1800) found')
        off = max(cands)[1]
        print('table at file offset 0x%x (%d candidates)' % (off, len(cands)))
    return data, off


def count(data, i):
    """Number of entries of a well-formed table starting at i, else -1."""
    n = 0
    while i + 2 <= len(data):
        size = int.from_bytes(data[i:i + 2], 'little')
        if size == 0:
            return n
        if size < 8 or i + size > len(data):
            return -1
        n, i = n + 1, i + size
    return -1


def dump(data, off=0):
    i = off
    while True:
        size, flags, handle = (int.from_bytes(data[i + k:i + k + 2], 'little') for k in (0, 2, 4))
        if size == 0:
            print('end at offset 0x%x' % i)
            return
        if size < 8 or i + size > len(data):
            sys.exit('bad entry at offset 0x%x (size %d)' % (i, size))
        ul = 16 if flags & UUID128 else 2
        uuid = data[i + 6:i + 6 + ul][::-1].hex()
        val = data[i + 6 + ul:i + size]
        props = [n for b, n in PROP_NAMES if flags & b]
        if flags >> 12:
            props.append('ENC_KEY_SIZE_%d' % ((flags >> 12) + 1))
        kind = {'2800': 'SERVICE', '2803': 'CHAR', '2902': 'CCCD', '2908': 'REPORT_REF'}.get(uuid, 'VALUE')
        print('0x%04x %-10s %-6s flags=0x%04x %-40s %s' % (handle, kind, uuid, flags, '|'.join(props), val.hex(' ')))
        i += size


if __name__ == '__main__':
    if sys.argv[1:2] == ['gen']:
        sys.stdout.write(header())
    elif sys.argv[1:2] == ['dump'] and len(sys.argv) in (3, 4):
        dump(*load(sys.argv[2], int(sys.argv[3], 0) if len(sys.argv) == 4 else None))
    else:
        sys.exit(__doc__)
